#!/usr/bin/env python3
"""Generate config/images.txt from the overlay table in SLUS_011.81.

    python3 tools/gen_images.py game > config/images.txt

Torneko keeps its code overlays in DISK_MM.CD. The executable's table for that archive
(0x800B327C) is: count, 0, archive name, 0, then per file {sector, size, sectors, 0, name}.
The loader (0x800251A0) is called with a fixed destination per overlay:
  MK.PRG, DG.PRG                         -> 0x80128000
  MV.PRG, DM.PRG, ED.PRG, LD.PRG, BN.PRG -> 0x8013C000
An overlay is code followed by its data; the image covers only the code part (up to the last
`jr ra` of the run of code at its start), so the data is never swept for functions.
"""
import os
import struct
import sys

game = sys.argv[1]
exe = open(os.path.join(game, 'SLUS_011.81'), 'rb').read()[0x800:]
w = lambda a: struct.unpack_from('<I', exe, a - 0x80010000)[0]


def cstr(a):
    o = a - 0x80010000
    return exe[o:exe.index(b'\0', o)].decode()


LOAD = {'MK': 0x80128000, 'DG': 0x80128000, 'MV': 0x8013C000, 'DM': 0x8013C000,
        'ED': 0x8013C000, 'LD': 0x8013C000, 'BN': 0x8013C000}
TABLE = 0x800B327C


def code_size(data):
    """Length of the code at the start of an overlay: up to the last jr ra (+ delay slot)
    before a stretch of 24 KB without one."""
    last = None
    for i in range(len(data) // 4):
        if struct.unpack_from('<I', data, 4 * i)[0] == 0x03E00008:
            if last is not None and 4 * i - last > 0x6000:
                break
            last = 4 * i
    return (last + 8) if last is not None else 0


out = ['# Code images for the recompiler (see src/recomp.py). Generated by tools/gen_images.py.',
       '#   exe <file>',
       '#   ovl <file> <load address> <host exe> <archive> <offset> <size>',
       'exe SLUS_011.81']
arc = open(os.path.join(game, 'DISK_MM.CD'), 'rb').read()
for k in range(w(TABLE)):
    e = TABLE + 16 + 20 * k
    sec, size, name = w(e), w(e + 4), cstr(w(e + 16))
    short = name.strip('\\').split('.')[0]
    data = arc[sec * 0x800:sec * 0x800 + size]
    if code_size(data) < 0x100:   # DG.PRG is shop/dialogue text, no code
        out.append('# %s: no code' % name)
        continue
    out.append('ovl overlays/%s.bin %08x SLUS_011.81 DISK_MM.CD %07x %06x   # %s, %d bytes' %
               (short, LOAD[short], sec * 0x800, code_size(data), name, size))
print('\n'.join(out))
